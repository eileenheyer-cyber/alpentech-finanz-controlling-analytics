"""
Validation script for the AlpenTech GmbH controlling dataset.
Run after generate_dataset.py. Writes data_validation_report.md.
"""

import pandas as pd
import os

OUT_DIR = os.path.dirname(os.path.abspath(__file__))

def load(name, **kw):
    return pd.read_csv(os.path.join(OUT_DIR, name), **kw)

dim_company = load("dim_company.csv")
dim_date = load("dim_date.csv")
dim_bu = load("dim_business_unit.csv")
dim_cc = load("dim_cost_center.csv")
dim_acc = load("dim_account.csv")
dim_cust = load("dim_customer.csv")
dim_prod = load("dim_product.csv")
fact_actual = load("fact_actual.csv")
fact_budget = load("fact_budget.csv")
fact_forecast = load("fact_forecast.csv")

REV_IDS = [4000, 4100, 4200]
lines = []
issues = []

def log(msg):
    lines.append(msg)

def check(label, condition):
    status = "PASS" if condition else "FAIL"
    log(f"- [{status}] {label}")
    if not condition:
        issues.append(label)

log("# AlpenTech GmbH – Data Validation Report\n")
log(f"Generated by `validate_dataset.py`.\n")

# ---------------------------------------------------------------------------
log("## 1. Row counts\n")
for name, df in [
    ("dim_company", dim_company), ("dim_date", dim_date), ("dim_business_unit", dim_bu),
    ("dim_cost_center", dim_cc), ("dim_account", dim_acc), ("dim_customer", dim_cust),
    ("dim_product", dim_prod), ("fact_actual", fact_actual), ("fact_budget", fact_budget),
    ("fact_forecast", fact_forecast),
]:
    log(f"- `{name}`: {len(df):,} rows")

# ---------------------------------------------------------------------------
log("\n## 2. Primary key uniqueness\n")
check("dim_date.date_id unique", not dim_date.date_id.duplicated().any())
check("dim_cost_center.cost_center_id unique", not dim_cc.cost_center_id.duplicated().any())
check("dim_account.account_id unique", not dim_acc.account_id.duplicated().any())
check("dim_customer.customer_id unique", not dim_cust.customer_id.duplicated().any())
check("dim_product.product_id unique", not dim_prod.product_id.duplicated().any())
check("dim_business_unit.business_unit_id unique", not dim_bu.business_unit_id.duplicated().any())
check("fact_actual.transaction_id unique", not fact_actual.transaction_id.duplicated().any())
check("fact_budget (date, cost_center_id, account_id) unique", not fact_budget.duplicated(subset=["date", "cost_center_id", "account_id"]).any())
check("fact_forecast (date, cost_center_id, account_id) unique", not fact_forecast.duplicated(subset=["date", "cost_center_id", "account_id"]).any())

# ---------------------------------------------------------------------------
log("\n## 3. Missing values\n")
for name, df in [("fact_actual", fact_actual), ("fact_budget", fact_budget), ("fact_forecast", fact_forecast)]:
    check(f"{name} has no null values in any column", df.isnull().sum().sum() == 0)

# ---------------------------------------------------------------------------
log("\n## 4. Foreign key integrity\n")
check("fact_actual.cost_center_id all valid", fact_actual.cost_center_id.isin(dim_cc.cost_center_id).all())
check("fact_actual.account_id all valid", fact_actual.account_id.isin(dim_acc.account_id).all())
check("fact_actual.business_unit_id all valid", fact_actual.business_unit_id.isin(dim_bu.business_unit_id).all())
check("fact_actual.customer_id all valid", fact_actual.customer_id.isin(dim_cust.customer_id).all())
check("fact_actual.product_id all valid", fact_actual.product_id.isin(dim_prod.product_id).all())
check("fact_actual.date all present in dim_date", fact_actual.date.astype(str).isin(dim_date.date.astype(str)).all())
check("fact_budget.cost_center_id all valid", fact_budget.cost_center_id.isin(dim_cc.cost_center_id).all())
check("fact_budget.account_id all valid", fact_budget.account_id.isin(dim_acc.account_id).all())
check("fact_budget.date all present in dim_date", fact_budget.date.astype(str).isin(dim_date.date.astype(str)).all())
check("fact_forecast.cost_center_id all valid", fact_forecast.cost_center_id.isin(dim_cc.cost_center_id).all())
check("fact_forecast.account_id all valid", fact_forecast.account_id.isin(dim_acc.account_id).all())
check("fact_forecast.date all present in dim_date", fact_forecast.date.astype(str).isin(dim_date.date.astype(str)).all())

# cost-center -> account combinations actually used should match the intended map (no stray combos)
check("cost_center_id present on every account assigned to it consistently with business unit mapping",
      fact_actual.merge(dim_cc, on="cost_center_id").business_unit_id_x.equals(
          fact_actual.merge(dim_cc, on="cost_center_id").business_unit_id_y
      ) if "business_unit_id_x" in fact_actual.merge(dim_cc, on="cost_center_id").columns else True)

# ---------------------------------------------------------------------------
log("\n## 5. Date validity\n")
check("dim_date covers 2023-01-01 to 2025-12-31 with no gaps (1096 days)", len(dim_date) == 1096)
check("fact_actual dates within 2023-01-01 to 2025-12-31", (pd.to_datetime(fact_actual.date) >= "2023-01-01").all() and (pd.to_datetime(fact_actual.date) <= "2025-12-31").all())
check("fact_actual transactions fall only on business days (Mon-Fri)", (pd.to_datetime(fact_actual.date).dt.dayofweek < 5).all())
check("fact_budget/fact_forecast dates are all first-of-month", (pd.to_datetime(fact_budget.date).dt.day == 1).all() and (pd.to_datetime(fact_forecast.date).dt.day == 1).all())

# ---------------------------------------------------------------------------
log("\n## 6. Sign convention consistency (Revenue positive / Expense negative)\n")
check("fact_actual: all Revenue-account rows are positive", (fact_actual[fact_actual.account_id.isin(REV_IDS)].amount > 0).all())
check("fact_actual: all Expense-account rows are negative", (fact_actual[~fact_actual.account_id.isin(REV_IDS)].amount < 0).all())
check("fact_budget: all Revenue-account rows are positive", (fact_budget[fact_budget.account_id.isin(REV_IDS)].budget_amount > 0).all())
check("fact_budget: all Expense-account rows are negative", (fact_budget[~fact_budget.account_id.isin(REV_IDS)].budget_amount < 0).all())
check("fact_forecast: all Revenue-account rows are positive", (fact_forecast[fact_forecast.account_id.isin(REV_IDS)].forecast_amount > 0).all())
check("fact_forecast: all Expense-account rows are negative", (fact_forecast[~fact_forecast.account_id.isin(REV_IDS)].forecast_amount < 0).all())

# ---------------------------------------------------------------------------
log("\n## 7. Revenue/customer/product attribution rules\n")
check("customer_id populated only meaningfully on Revenue rows (else CUST-NA)", (fact_actual[~fact_actual.account_id.isin(REV_IDS)].customer_id == "CUST-NA").all())
check("product_id is CUST-NA-equivalent (PROD-NA) on all non-Revenue, non-RawMaterial rows",
      (fact_actual[~fact_actual.account_id.isin(REV_IDS + [5000])].product_id == "PROD-NA").all())

# ---------------------------------------------------------------------------
log("\n## 8. Budget vs Actual reconciliation (annual totals, EUR)\n")

fa = fact_actual.copy()
fa["year"] = pd.to_datetime(fa.date).dt.year
fb = fact_budget.copy()
fb["year"] = pd.to_datetime(fb.date).dt.year
ff = fact_forecast.copy()
ff["year"] = pd.to_datetime(ff.date).dt.year

rev_a = fa[fa.account_id.isin(REV_IDS)].groupby("year").amount.sum()
rev_b = fb[fb.account_id.isin(REV_IDS)].groupby("year").budget_amount.sum()
exp_a = fa[~fa.account_id.isin(REV_IDS)].groupby("year").amount.sum()
exp_b = fb[~fb.account_id.isin(REV_IDS)].groupby("year").budget_amount.sum()
result_a = rev_a + exp_a
result_b = rev_b + exp_b
margin_a = (result_a / rev_a * 100).round(2)

log("| Year | Revenue (Actual) | Revenue (Budget) | Total Costs (Actual) | Betriebsergebnis (Actual) | Betriebsergebnis (Budget) | EBIT-Marge (Actual) |")
log("|---|---|---|---|---|---|---|")
for y in [2023, 2024, 2025]:
    log(f"| {y} | {rev_a[y]:,.0f} | {rev_b[y]:,.0f} | {exp_a[y]:,.0f} | {result_a[y]:,.0f} | {result_b[y]:,.0f} | {margin_a[y]:.2f}% |")

# ---------------------------------------------------------------------------
log("\n## 9. Scenario evidence (as generated)\n")

def yearly(df, val_col, **filters):
    sub = df
    for k, v in filters.items():
        sub = sub[sub[k] == v]
    return sub.groupby("year")[val_col].sum().astype(float)

def d(series):
    return {int(k): round(float(v), 0) for k, v in series.items()}

energy_a = yearly(fa, "amount", account_id=5300)
energy_b = yearly(fb, "budget_amount", account_id=5300)
log("**Scenario 1 – Energy cost increase:**")
log(f"- Actual: {d(energy_a)}")
log(f"- Budget: {d(energy_b)}")
log(f"- Actual-vs-budget variance 2025: {(energy_a[2025]/energy_b[2025]-1)*100:.1f}%\n")

log("**Scenario 2 – Marketing campaign overspend (2024 monthly, account 5700):**")
mkt_2024 = fa[(fa.account_id == 5700) & (fa.year == 2024)].copy()
mkt_2024["month"] = pd.to_datetime(mkt_2024.date).dt.month
log(f"- Monthly actual spend: {d(mkt_2024.groupby('month').amount.sum())}\n")

pers_a = yearly(fa, "amount", account_id=5500)
log("**Scenario 3 – Gradual personnel cost growth:**")
log(f"- Actual by year: {d(pers_a)}\n")

log_a = yearly(fa, "amount", account_id=5200)
log_b = yearly(fb, "budget_amount", account_id=5200)
log("**Scenario 4/7 – Logistics costs outgrow revenue, cost center consistently over budget:**")
log(f"- Actual: {d(log_a)}")
log(f"- Budget: {d(log_b)}")
log(f"- Variance vs budget by year (%): {d(((log_a/log_b-1)*100))}\n")

db1_p1 = fa[(fa.account_id == 4000) & (fa.product_id.isin(["PROD-01", "PROD-02"]))].groupby("year").amount.sum() \
    + fa[(fa.account_id == 5000) & (fa.product_id.isin(["PROD-01", "PROD-02"]))].groupby("year").amount.sum()
log("**Scenario 5 – Margin pressure on Machinery Components in 2025 (Deckungsbeitrag I):**")
log(f"- DB1 (Machinery Components, PROD-01+PROD-02) by year: {d(db1_p1)}\n")

it_a = yearly(fa, "amount", cost_center_id=6000)
it_b = yearly(fb, "budget_amount", cost_center_id=6000)
log("**Scenario 6 – Planned IT/cloud investment:**")
log(f"- IT cost center actual: {d(it_a)}")
log(f"- IT cost center budget: {d(it_b)}\n")

proc_a = yearly(fa, "amount", cost_center_id=2000)
proc_b = yearly(fb, "budget_amount", cost_center_id=2000)
log("**Scenario 8 – Procurement consistently beats budget:**")
log(f"- Procurement actual: {d(proc_a)}")
log(f"- Procurement budget: {d(proc_b)}")
log(f"- Actual is below budget in all 3 years: {bool((proc_a.abs() < proc_b.abs()).all())}\n")

# ---------------------------------------------------------------------------
log("\n## 10. Forecast logic sanity\n")
merged = ff.merge(fb, on=["date", "cost_center_id", "account_id"], suffixes=("", "_b"))
fa_month = fa.copy()
fa_month["date"] = pd.to_datetime(fa_month.date).dt.to_period("M").dt.to_timestamp().dt.strftime("%Y-%m-%d")
fa_month = fa_month.groupby(["date", "cost_center_id", "account_id"], as_index=False).amount.sum()
merged = merged.merge(fa_month, on=["date", "cost_center_id", "account_id"], how="left")
merged["amount"] = merged["amount"].fillna(0)
merged["month"] = pd.to_datetime(merged.date).dt.month
h1 = merged[merged.month <= 6]
h1_diff = (h1.forecast_amount - h1.amount).abs().max()
check("H1 forecast equals actual (Hochrechnung 'closed months')", h1_diff < 0.01)

result_f = (ff[ff.account_id.isin(REV_IDS)].groupby("year").forecast_amount.sum()
            + ff[~ff.account_id.isin(REV_IDS)].groupby("year").forecast_amount.sum())
log("\n**Full-year Betriebsergebnis: Budget vs Forecast vs Actual**\n")
log("| Year | Budget | Forecast | Actual |")
log("|---|---|---|---|")
for y in [2023, 2024, 2025]:
    log(f"| {y} | {result_b[y]:,.0f} | {result_f[y]:,.0f} | {result_a[y]:,.0f} |")

# ---------------------------------------------------------------------------
log("\n## 11. Overall result\n")
if issues:
    log(f"**{len(issues)} check(s) FAILED:**")
    for i in issues:
        log(f"- {i}")
else:
    log("**All validation checks passed.** The dataset is clean, internally consistent, and free of broken foreign keys, missing values, duplicate keys, or sign-convention violations.")

report = "\n".join(lines)
with open(os.path.join(OUT_DIR, "data_validation_report.md"), "w") as f:
    f.write(report + "\n")

print(report)
print(f"\n{'ALL CHECKS PASSED' if not issues else f'{len(issues)} CHECK(S) FAILED'}")
